import Foundation
import SwiftUI

enum Category: String, CaseIterable, Identifiable {
    case build = "Build Artifacts"
    case caches = "IDE & Tool Caches"
    case ai = "AI & Model Data"
    case general = "Large & General"

    var id: String { rawValue }

    var icon: String {
        switch self {
        case .build: return "hammer.fill"
        case .caches: return "wrench.and.screwdriver.fill"
        case .ai: return "brain"
        case .general: return "internaldrive.fill"
        }
    }

    var color: Color {
        switch self {
        case .build: return .blue
        case .caches: return .purple
        case .ai: return .mint
        case .general: return .orange
        }
    }

    var subtitle: String {
        switch self {
        case .build: return "node_modules, .build, target, venvs… inside project folders"
        case .caches: return "Xcode, VS Code, Homebrew, npm/pip, Docker, simulators, app caches…"
        case .ai: return "Ollama, HuggingFace, LM Studio and other model caches"
        case .general: return "Downloads, Trash, app caches, logs, large files, backups"
        }
    }
}

enum AppMode: String, CaseIterable, Identifiable {
    case storage = "Storage"
    case processes = "Processes"

    var id: String { rawValue }
}

enum KindFilter: String, CaseIterable, Identifiable {
    case all = "All"
    case files = "Files"
    case folders = "Folders"

    var id: String { rawValue }
}

struct CleanableItem: Identifiable, Hashable {
    var id: String { path.path }
    let path: URL
    let name: String
    let category: Category
    let isDirectory: Bool
    let detail: String          // built-in explanation
    let caution: Bool           // deleting needs extra thought / re-download
    var size: Int64
    var isSelected: Bool
}

extension Int64 {
    var bytesFormatted: String {
        ByteCountFormatter.string(fromByteCount: self, countStyle: .file)
    }
}

