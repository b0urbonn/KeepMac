    static func generalItem(name: String, path: URL, isDir: Bool) -> (String, Bool) {
        let p = path.path
        let home = FileManager.default.homeDirectoryForCurrentUser.path
        if p.hasPrefix(home + "/Downloads") {
            return ("A file in your Downloads folder. This is your own file — deleting is permanent, so be sure you no longer need it.", true)
        }
        if p.hasPrefix(home + "/.Trash") {
            return ("An item already in the Trash. Deleting it here permanently erases it and frees the space.", false)
        }
        if p.hasPrefix(home + "/Library/Logs") {
            return ("Log files written by an app or the system. Safe to delete.", false)
        }
        if p.hasPrefix(home + "/Library/Caches") {
            return ("Cache files written by an app. Safe to delete — the app recreates them as needed.", false)
        }
        if p.hasPrefix(home + "/Library/Application Support/MobileSync") {
            return ("A local iPhone/iPad backup. Only delete if you're sure you don't need this backup.", true)
        }
        return (isDir ? "A large folder found on your disk." : "A large file found on your disk. Review it before deleting — deletion is permanent.", true)
    }
